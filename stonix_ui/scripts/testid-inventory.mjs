#!/usr/bin/env node
/**
 * Full testid inventory (X-69). Lists literals under src/ and checks tests/testids.baseline.txt.
 */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src');
const baselinePath = path.join(root, 'tests', 'testids.baseline.txt');

const REQUIRED = [
  'agent-audio-visualizer',
  'voice-status',
  'voice-toggle',
  'assistant-agent-listening',
  'enable-audio',
  'voice-wake-agent',
  'voice-take-over',
];

const DYNAMIC_FAMILIES = [
  'settings-<field>',
  'settings-status-<field>',
  'settings-agent-pending-<field>',
  'mobile-tab-<tab>',
  'vitals-pc',
  'vitals-vps',
  'vitals-pc-updated',
  'vitals-vps-updated',
  'vitals-pc-stale',
  'vitals-vps-stale',
  'chip-*',
  'chip-*-spinner',
  'intelligence-history-<id>',
  'intelligence-lan',
  'intelligence-lan-audio',
  'flow-*-status',
];

async function walk(dir, out = []) {
  const entries = await readdir(dir, { withFileTypes: true });
  for (const ent of entries) {
    const full = path.join(dir, ent.name);
    if (ent.isDirectory()) await walk(full, out);
    else if (/\.(tsx?|jsx?)$/.test(ent.name)) out.push(full);
  }
  return out;
}

function parseBaseline(text) {
  const staticIds = [];
  const families = [];
  const retired = new Map();
  let section = 'static';
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    if (line === 'families:') {
      section = 'families';
      continue;
    }
    if (line === 'retired:') {
      section = 'retired';
      continue;
    }
    if (section === 'static') staticIds.push(line);
    else if (section === 'families') families.push(line);
    else if (section === 'retired') {
      const idx = line.indexOf(':');
      if (idx > 0) retired.set(line.slice(0, idx).trim(), line.slice(idx + 1).trim());
    }
  }
  return { staticIds, families, retired };
}

const files = await walk(srcDir);
const ids = new Set();
const re = /data-testid=["']([^"']+)["']/g;
for (const file of files) {
  const text = await readFile(file, 'utf8');
  let m;
  while ((m = re.exec(text))) ids.add(m[1]);
}

const sorted = [...ids].sort();
const check = process.argv.includes('--check');
const writeBaseline = process.argv.includes('--write-baseline');

if (writeBaseline) {
  const body = [
    '# Static data-testid literals (generated by testid-inventory.mjs --write-baseline)',
    ...sorted,
    '',
    'families:',
    ...DYNAMIC_FAMILIES,
    '',
    'retired:',
    'ops-drawer-backdrop: tablet ops drawer removed; ops-drawer-toggle remains as nav alias (spec v2 §17)',
    '',
  ].join('\n');
  await writeFile(baselinePath, body, 'utf8');
  console.log(`Wrote ${sorted.length} static ids to ${path.relative(root, baselinePath)}`);
  process.exit(0);
}

console.log(`Found ${sorted.length} data-testid literals in stonix_ui/src`);

if (!check) {
  for (const id of sorted) console.log(id);
  process.exit(0);
}

let baselineText;
try {
  baselineText = await readFile(baselinePath, 'utf8');
} catch {
  console.error('Missing baseline:', path.relative(root, baselinePath));
  console.error('Run: node stonix_ui/scripts/testid-inventory.mjs --write-baseline');
  process.exit(1);
}

const baseline = parseBaseline(baselineText);
const missingRequired = REQUIRED.filter(id => !ids.has(id));
if (missingRequired.length) {
  console.error('Missing required voice testids:', missingRequired.join(', '));
  process.exit(1);
}

const missingStatic = baseline.staticIds.filter(id => !ids.has(id) && !baseline.retired.has(id));
const extraStatic = sorted.filter(id => !baseline.staticIds.includes(id) && !baseline.retired.has(id));

if (missingStatic.length) {
  console.error('Baseline ids missing from src:', missingStatic.join(', '));
  process.exit(1);
}

if (extraStatic.length) {
  console.error('New testids not in baseline (add to testids.baseline.txt):', extraStatic.join(', '));
  process.exit(1);
}

for (const fam of baseline.families) {
  if (!DYNAMIC_FAMILIES.includes(fam)) {
    console.error('Unknown family in baseline:', fam);
    process.exit(1);
  }
}

for (const fam of DYNAMIC_FAMILIES) {
  if (!baseline.families.includes(fam)) {
    console.error('Baseline missing dynamic family:', fam);
    process.exit(1);
  }
}

console.log(
  `testid inventory check passed (${sorted.length} static, ${baseline.families.length} families, ${baseline.retired.size} retired)`,
);
